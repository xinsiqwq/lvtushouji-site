import type { Lut3D } from './grade-types';

function clamp01(v: number): number {
  if (v <= 0) return 0;
  if (v >= 1) return 1;
  return v;
}

function parseTriplet(parts: string[], lineNo: number, label: string): [number, number, number] {
  if (parts.length < 3) {
    throw new Error(`第 ${lineNo} 行 ${label} 缺少 RGB 三个数值`);
  }
  const r = Number(parts[0]);
  const g = Number(parts[1]);
  const b = Number(parts[2]);
  if (!Number.isFinite(r) || !Number.isFinite(g) || !Number.isFinite(b)) {
    throw new Error(`第 ${lineNo} 行 ${label} 包含无效数值`);
  }
  return [r, g, b];
}

/**
 * Parse a standard Adobe `.cube` 3D LUT file (Specification 1.0).
 * Supports `TITLE`, `LUT_3D_SIZE` (2..65), `DOMAIN_MIN`, `DOMAIN_MAX`, comments (`#`), and blank lines.
 * Data rows are stored in Adobe Cube red-fastest order: index = ((b * size + g) * size + r) * 3.
 */
export function parseCubeLut(text: string, fallbackTitle = '未命名 3D LUT'): Lut3D {
  if (typeof text !== 'string' || text.trim().length === 0) {
    throw new Error('LUT 文件为空，请选择有效的 .cube 3D LUT 文件');
  }

  const normalized = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  const lines = normalized.split(/\r?\n/);

  let title = fallbackTitle;
  let size = 0;
  let has1D = false;
  let domainMin: [number, number, number] = [0, 0, 0];
  let domainMax: [number, number, number] = [1, 1, 1];
  const rawValues: number[] = [];

  for (let i = 0; i < lines.length; i++) {
    const lineNo = i + 1;
    let line = lines[i];
    const hashIdx = line.indexOf('#');
    if (hashIdx >= 0) {
      line = line.slice(0, hashIdx);
    }
    line = line.trim();
    if (!line) continue;

    if (line.startsWith('TITLE')) {
      const rest = line.slice(5).trim();
      if (rest.length >= 2 && rest.startsWith('"') && rest.endsWith('"')) {
        title = rest.slice(1, -1).trim() || fallbackTitle;
      } else if (rest.length > 0) {
        title = rest;
      }
      continue;
    }

    const parts = line.split(/\s+/);
    const keyword = parts[0];

    if (keyword === 'LUT_1D_SIZE') {
      has1D = true;
      continue;
    }

    if (keyword === 'LUT_3D_SIZE') {
      const parsed = Number(parts[1]);
      if (!Number.isInteger(parsed) || parsed < 2 || parsed > 65) {
        throw new Error(`无效的 LUT_3D_SIZE（第 ${lineNo} 行）：需为 2 至 65 之间的整数`);
      }
      size = parsed;
      continue;
    }

    if (keyword === 'DOMAIN_MIN') {
      domainMin = parseTriplet(parts.slice(1), lineNo, 'DOMAIN_MIN');
      continue;
    }

    if (keyword === 'DOMAIN_MAX') {
      domainMax = parseTriplet(parts.slice(1), lineNo, 'DOMAIN_MAX');
      continue;
    }

    if (keyword === 'LUT_1D_INPUT_RANGE' || keyword === 'LUT_3D_INPUT_RANGE') {
      continue;
    }

    // Data triplet row
    if (parts.length !== 3) {
      throw new Error(`第 ${lineNo} 行格式无法识别，请确认文件为标准 Adobe .cube 格式`);
    }
    const [r, g, b] = parseTriplet(parts, lineNo, '色表数据');
    rawValues.push(r, g, b);
  }

  if (size === 0) {
    if (has1D) {
      throw new Error('暂仅支持 3D LUT（LUT_3D_SIZE），不支持纯 1D LUT 文件');
    }
    throw new Error('缺少 LUT_3D_SIZE 声明，请确认文件为标准 3D .cube 文件');
  }

  for (let c = 0; c < 3; c++) {
    if (domainMax[c] <= domainMin[c]) {
      throw new Error('DOMAIN_MAX 必须大于 DOMAIN_MIN');
    }
  }

  const expectedPoints = size * size * size;
  const actualPoints = rawValues.length / 3;
  if (actualPoints !== expectedPoints) {
    throw new Error(
      `3D LUT 数据行数不匹配：LUT_3D_SIZE ${size} 需要 ${expectedPoints} 行，实际解析到 ${actualPoints} 行`,
    );
  }

  return {
    title,
    size,
    data: Float32Array.from(rawValues),
    domainMin,
    domainMax,
  };
}

/**
 * Serialize a `Lut3D` into standard Adobe `.cube` 3D text format (6 decimal places, red-fastest order).
 */
export function serializeCubeLut(lut: Lut3D, title?: string): string {
  const { size, data, domainMin, domainMax } = lut;
  if (!Number.isInteger(size) || size < 2 || size > 65) {
    throw new Error(`无法导出无效尺寸的 3D LUT：${size}`);
  }
  const expectedLen = size * size * size * 3;
  if (data.length !== expectedLen) {
    throw new Error(`3D LUT 数据长度异常：期望 ${expectedLen}，实际 ${data.length}`);
  }

  const safeTitle = (title ?? lut.title ?? 'Mercury Grade LUT')
    .replace(/[\r\n"]+/g, ' ')
    .trim() || 'Mercury Grade LUT';

  const lines: string[] = [
    '# Generated by 旅途手记 · 水星工具箱 Color Science Engine',
    `TITLE "${safeTitle}"`,
    `DOMAIN_MIN ${domainMin[0].toFixed(6)} ${domainMin[1].toFixed(6)} ${domainMin[2].toFixed(6)}`,
    `DOMAIN_MAX ${domainMax[0].toFixed(6)} ${domainMax[1].toFixed(6)} ${domainMax[2].toFixed(6)}`,
    `LUT_3D_SIZE ${size}`,
  ];

  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const idx = ((b * size + g) * size + r) * 3;
        lines.push(
          `${data[idx].toFixed(6)} ${data[idx + 1].toFixed(6)} ${data[idx + 2].toFixed(6)}`,
        );
      }
    }
  }

  return `${lines.join('\n')}\n`;
}

/**
 * Evaluate a `Lut3D` on the CPU using exact 8-corner trilinear interpolation.
 */
export function evaluateLut3D(
  lut: Lut3D,
  r: number,
  g: number,
  b: number,
): [number, number, number] {
  const { size, data, domainMin, domainMax } = lut;
  const maxIdx = size - 1;

  const nr = clamp01((r - domainMin[0]) / (domainMax[0] - domainMin[0])) * maxIdx;
  const ng = clamp01((g - domainMin[1]) / (domainMax[1] - domainMin[1])) * maxIdx;
  const nb = clamp01((b - domainMin[2]) / (domainMax[2] - domainMin[2])) * maxIdx;

  const r0 = Math.floor(nr);
  const g0 = Math.floor(ng);
  const b0 = Math.floor(nb);
  const r1 = r0 < maxIdx ? r0 + 1 : maxIdx;
  const g1 = g0 < maxIdx ? g0 + 1 : maxIdx;
  const b1 = b0 < maxIdx ? b0 + 1 : maxIdx;

  const fr = nr - r0;
  const fg = ng - g0;
  const fb = nb - b0;

  const idx000 = ((b0 * size + g0) * size + r0) * 3;
  const idx100 = ((b0 * size + g0) * size + r1) * 3;
  const idx010 = ((b0 * size + g1) * size + r0) * 3;
  const idx110 = ((b0 * size + g1) * size + r1) * 3;
  const idx001 = ((b1 * size + g0) * size + r0) * 3;
  const idx101 = ((b1 * size + g0) * size + r1) * 3;
  const idx011 = ((b1 * size + g1) * size + r0) * 3;
  const idx111 = ((b1 * size + g1) * size + r1) * 3;

  const out: [number, number, number] = [0, 0, 0];
  for (let c = 0; c < 3; c++) {
    const c00 = data[idx000 + c] + (data[idx100 + c] - data[idx000 + c]) * fr;
    const c10 = data[idx010 + c] + (data[idx110 + c] - data[idx010 + c]) * fr;
    const c01 = data[idx001 + c] + (data[idx101 + c] - data[idx001 + c]) * fr;
    const c11 = data[idx011 + c] + (data[idx111 + c] - data[idx011 + c]) * fr;

    const c0 = c00 + (c10 - c00) * fg;
    const c1 = c01 + (c11 - c01) * fg;
    out[c] = c0 + (c1 - c0) * fb;
  }

  return out;
}

/**
 * Pack an N×N×N 3D LUT into a 2D RGBA8 texture atlas of size (N*N) × N
 * with coordinates `x = b * N + r`, `y = g`.
 * Compatible with both WebGL1 and WebGL2.
 */
export function packLut3DTo2DAtlas(lut: Lut3D): {
  width: number;
  height: number;
  size: number;
  pixels: Uint8Array;
} {
  const { size, data } = lut;
  const width = size * size;
  const height = size;
  const pixels = new Uint8Array(width * height * 4);

  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const srcIdx = ((b * size + g) * size + r) * 3;
        const x = b * size + r;
        const y = g;
        const dstIdx = (y * width + x) * 4;
        pixels[dstIdx] = Math.round(clamp01(data[srcIdx]) * 255);
        pixels[dstIdx + 1] = Math.round(clamp01(data[srcIdx + 1]) * 255);
        pixels[dstIdx + 2] = Math.round(clamp01(data[srcIdx + 2]) * 255);
        pixels[dstIdx + 3] = 255;
      }
    }
  }

  return { width, height, size, pixels };
}

/**
 * Create an identity N×N×N 3D LUT.
 */
export function createIdentityLut3D(size = 33, title = 'Identity 3D LUT'): Lut3D {
  const data = new Float32Array(size * size * size * 3);
  const denom = size - 1;
  for (let b = 0; b < size; b++) {
    for (let g = 0; g < size; g++) {
      for (let r = 0; r < size; r++) {
        const idx = ((b * size + g) * size + r) * 3;
        data[idx] = r / denom;
        data[idx + 1] = g / denom;
        data[idx + 2] = b / denom;
      }
    }
  }
  return {
    title,
    size,
    data,
    domainMin: [0, 0, 0],
    domainMax: [1, 1, 1],
  };
}

/**
 * Resample a 3D LUT to another grid size (e.g. downsampling 65³ to 33³ for constrained WebGL1 GPUs).
 */
export function resampleLut3D(lut: Lut3D, targetSize: number): Lut3D {
  if (lut.size === targetSize) return lut;
  const data = new Float32Array(targetSize * targetSize * targetSize * 3);
  const denom = targetSize - 1;
  const [minR, minG, minB] = lut.domainMin;
  const spanR = lut.domainMax[0] - minR;
  const spanG = lut.domainMax[1] - minG;
  const spanB = lut.domainMax[2] - minB;

  for (let b = 0; b < targetSize; b++) {
    const vb = minB + (b / denom) * spanB;
    for (let g = 0; g < targetSize; g++) {
      const vg = minG + (g / denom) * spanG;
      for (let r = 0; r < targetSize; r++) {
        const vr = minR + (r / denom) * spanR;
        const [or, og, ob] = evaluateLut3D(lut, vr, vg, vb);
        const idx = ((b * targetSize + g) * targetSize + r) * 3;
        data[idx] = or;
        data[idx + 1] = og;
        data[idx + 2] = ob;
      }
    }
  }

  return {
    title: lut.title,
    size: targetSize,
    data,
    domainMin: [...lut.domainMin],
    domainMax: [...lut.domainMax],
  };
}
